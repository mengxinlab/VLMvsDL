"""Compute F3 run-averaged metrics for Gemini 3 Flash Preview.

For each AnnotationID, average the malignancy `confidence` across the five
curated F3 replicate files under `results/vlm/luna25_ablation/` and
`results/vlm/luna25_replicates/`. Then compute on that single averaged score:

  - ROC-AUC with 1000-iter stratified bootstrap 95% CI
  - PR-AUC with 1000-iter stratified bootstrap 95% CI
  - Sensitivity/specificity at threshold 0.5 and Youden-optimal threshold
  - Calibration: Brier, ECE, MCE (10 fixed-width bins)
  - Decision-curve net benefit at 5/10/15/20/50% thresholds
  - Paired DeLong P-values vs the seven supervised DL baselines
  - Paired DeLong P-value vs Brock on the 701-case complete-metadata subset

Outputs:
  results/vlm/f3a_mean_of5_predictions.csv
  results/vlm/f3a_mean_of5_metrics.json

"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats
from sklearn.metrics import (
    average_precision_score,
    brier_score_loss,
    roc_auc_score,
    roc_curve,
)

from benchmark.paths import (
    LUNA25_DL_PRED_DIR,
    VLM_RESULTS_DIR,
)

RNG = np.random.default_rng(42)
N_BOOT = 1000
N_CAL_BINS = 10
THRESHOLDS = [0.05, 0.10, 0.15, 0.20, 0.50]

F3_REPLICATES = [
    # Five F3 replicates at T=0; "00" is the primary representative run
    # (luna25_sensitivity/f3_gemini3flash_initial_t0_excluded.jsonl is a separate
    # exploratory temperature-0 run, reported only in the temperature ablation).
    "luna25_ablation/f3_gemini3flash_20shot_rich_metadata_run00.jsonl",
    "luna25_replicates/f3_gemini3flash_20shot_rich_metadata_run01.jsonl",
    "luna25_replicates/f3_gemini3flash_20shot_rich_metadata_run02.jsonl",
    "luna25_replicates/f3_gemini3flash_20shot_rich_metadata_run03.jsonl",
    "luna25_replicates/f3_gemini3flash_20shot_rich_metadata_run04.jsonl",
]

DL_FILES = {
    "STU-Net": "stunet_base_warmup_test_preds.csv",
    "EfficientNet-B0": "efficientnet_b0_baseline_test_preds.csv",
    "ResNet-18": "resnet18_baseline_test_preds.csv",
    "DenseNet-121": "densenet121_baseline_test_preds.csv",
    "ResNet-50": "resnet50_baseline_test_preds.csv",
    "Swin-UNETR": "swin_unetr_final_gpu_test_preds.csv",
    "ViT-Base": "vit_baseline_test_preds.csv",
}

# Single source of truth: verified McWilliams/PanCan Model 2b reimplementation
# generated by benchmark/posthoc_metadata_audits.py.
BROCK_CSV = VLM_RESULTS_DIR / "brock_pancan_predictions.csv"
BROCK_PROB_COL = "brock_prob_correct"


def load_vlm_jsonl(path: Path) -> pd.DataFrame:
    rows = []
    for line in path.read_text().splitlines():
        if not line.strip():
            continue
        rows.append(json.loads(line))
    df = pd.DataFrame(rows)
    df["confidence"] = pd.to_numeric(df["confidence"], errors="coerce")
    df = df[df["confidence"].between(0.0, 1.0)]
    return df.drop_duplicates("aid", keep="last")[["aid", "label", "confidence"]].reset_index(drop=True)


def load_dl(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    df = df[df["split"] == "test"].copy()
    df = df.rename(columns={"AnnotationID": "aid", "pred_prob": "confidence"})
    return df[["aid", "label", "confidence"]]


# DeLong implementation (Sun & Xu fast algorithm) ─────────────────────────────
def _compute_midrank(x):
    J = np.argsort(x)
    Z = x[J]
    N = len(x)
    T = np.zeros(N, dtype=float)
    i = 0
    while i < N:
        j = i
        while j < N and Z[j] == Z[i]:
            j += 1
        T[i:j] = 0.5 * (i + j - 1) + 1
        i = j
    T2 = np.empty(N, dtype=float)
    T2[J] = T
    return T2


def _fast_delong(predictions_sorted_transposed, label_1_count):
    m = label_1_count
    n = predictions_sorted_transposed.shape[1] - m
    positive_examples = predictions_sorted_transposed[:, :m]
    negative_examples = predictions_sorted_transposed[:, m:]
    k = predictions_sorted_transposed.shape[0]

    tx = np.empty([k, m], dtype=float)
    ty = np.empty([k, n], dtype=float)
    tz = np.empty([k, m + n], dtype=float)
    for r in range(k):
        tx[r, :] = _compute_midrank(positive_examples[r, :])
        ty[r, :] = _compute_midrank(negative_examples[r, :])
        tz[r, :] = _compute_midrank(predictions_sorted_transposed[r, :])
    aucs = tz[:, :m].sum(axis=1) / m / n - float(m + 1.0) / 2.0 / n
    v01 = (tz[:, :m] - tx[:, :]) / n
    v10 = 1.0 - (tz[:, m:] - ty[:, :]) / m
    sx = np.cov(v01)
    sy = np.cov(v10)
    delongcov = sx / m + sy / n
    return aucs, delongcov


def delong_p_value(y_true, score_a, score_b):
    """Two-sided paired DeLong p-value for AUC(A) vs AUC(B)."""
    order = (-y_true).argsort(kind="stable")
    label_1_count = int((y_true == 1).sum())
    preds_sorted = np.vstack([score_a[order], score_b[order]])
    aucs, cov = _fast_delong(preds_sorted, label_1_count)
    auc_diff = aucs[0] - aucs[1]
    var = cov[0, 0] + cov[1, 1] - 2 * cov[0, 1]
    if var <= 0:
        return float(aucs[0]), float(aucs[1]), float("nan")
    z = auc_diff / np.sqrt(var)
    p = 2 * (1 - stats.norm.cdf(abs(z)))
    return float(aucs[0]), float(aucs[1]), float(p)


# Bootstrap helpers ───────────────────────────────────────────────────────────
def stratified_bootstrap(y, s, metric_fn, n=N_BOOT):
    pos = np.where(y == 1)[0]
    neg = np.where(y == 0)[0]
    vals = np.empty(n)
    for i in range(n):
        p = RNG.choice(pos, size=len(pos), replace=True)
        q = RNG.choice(neg, size=len(neg), replace=True)
        idx = np.concatenate([p, q])
        try:
            vals[i] = metric_fn(y[idx], s[idx])
        except Exception:
            vals[i] = np.nan
    vals = vals[~np.isnan(vals)]
    lo, hi = np.quantile(vals, [0.025, 0.975])
    return float(lo), float(hi)


def expected_calibration_error(y_true, y_prob, n_bins=N_CAL_BINS):
    bins = np.linspace(0, 1, n_bins + 1)
    ece, mce = 0.0, 0.0
    for lo, hi in zip(bins[:-1], bins[1:]):
        mask = (y_prob > lo) & (y_prob <= hi) if lo > 0 else (y_prob >= lo) & (y_prob <= hi)
        if mask.sum() == 0:
            continue
        frac = mask.sum() / len(y_true)
        acc = y_true[mask].mean()
        conf = y_prob[mask].mean()
        gap = abs(acc - conf)
        ece += frac * gap
        mce = max(mce, gap)
    return float(ece), float(mce)


def youden_threshold(y, s):
    fpr, tpr, thr = roc_curve(y, s)
    j = tpr - fpr
    return float(thr[j.argmax()])


def sens_spec_at(y, s, t):
    yhat = (s >= t).astype(int)
    tp = int(((yhat == 1) & (y == 1)).sum())
    fn = int(((yhat == 0) & (y == 1)).sum())
    tn = int(((yhat == 0) & (y == 0)).sum())
    fp = int(((yhat == 1) & (y == 0)).sum())
    sens = tp / (tp + fn) if (tp + fn) else float("nan")
    spec = tn / (tn + fp) if (tn + fp) else float("nan")
    return sens, spec


def net_benefit(y, s, pt):
    n = len(y)
    yhat = (s >= pt).astype(int)
    tp = int(((yhat == 1) & (y == 1)).sum())
    fp = int(((yhat == 1) & (y == 0)).sum())
    return tp / n - (fp / n) * pt / (1 - pt)


# Main ────────────────────────────────────────────────────────────────────────
def main():
    # 1. Load five F3 runs and align per AID
    run_dfs = []
    individual_aucs = []
    for fn in F3_REPLICATES:
        df = load_vlm_jsonl(VLM_RESULTS_DIR / fn)
        run_dfs.append(df.set_index("aid"))
        individual_aucs.append(roc_auc_score(df["label"], df["confidence"]))
        print(f"  {fn}: n={len(df)}  AUC={individual_aucs[-1]:.4f}")

    aids = sorted(set.intersection(*[set(d.index) for d in run_dfs]))
    print(f"\nIntersection of AIDs across 5 runs: {len(aids)}")

    label = run_dfs[0].loc[aids, "label"].values.astype(int)
    scores = np.stack([d.loc[aids, "confidence"].values.astype(float) for d in run_dfs])
    avg = scores.mean(axis=0)
    print(f"Run-averaged confidence: mean={avg.mean():.4f}  std={avg.std():.4f}")

    # Save the run-averaged predictions, then reload and use the reloaded values
    # for all downstream metrics. CSV write/read loses ~1 ULP on some entries,
    # which can move ~0.001 of AUC through tie-breaking; computing from the
    # saved artifact guarantees readers reproduce the headline AUC byte-for-byte.
    out_csv = VLM_RESULTS_DIR / "f3a_mean_of5_predictions.csv"
    pd.DataFrame({"aid": aids, "label": label, "confidence": avg}).to_csv(
        out_csv, index=False, float_format="%.17g"
    )
    reloaded = pd.read_csv(out_csv).set_index("aid").loc[aids]
    label = reloaded["label"].values.astype(int)
    avg = reloaded["confidence"].values.astype(float)
    print(f"-> {out_csv}  (reloaded for AUC computation)")

    # 2. AUC / PR-AUC / CI on the run-averaged score
    auc = roc_auc_score(label, avg)
    auc_lo, auc_hi = stratified_bootstrap(label, avg, roc_auc_score)
    prauc = average_precision_score(label, avg)
    pr_lo, pr_hi = stratified_bootstrap(label, avg, average_precision_score)
    print(f"\nRun-averaged AUC = {auc:.4f}  (95% bootstrap CI {auc_lo:.4f}-{auc_hi:.4f})")
    print(f"Run-averaged PR-AUC = {prauc:.4f}  (95% bootstrap CI {pr_lo:.4f}-{pr_hi:.4f})")
    print(f"Individual-run AUCs: {[round(a, 4) for a in individual_aucs]}")
    print(f"Five-run AUC mean = {np.mean(individual_aucs):.4f}  s.d.={np.std(individual_aucs, ddof=1):.4f}")

    # 3. Operating points
    sens5, spec5 = sens_spec_at(label, avg, 0.5)
    t_y = youden_threshold(label, avg)
    sensy, specy = sens_spec_at(label, avg, t_y)
    print(f"\nAt 0.5: sens={sens5:.3f} spec={spec5:.3f}")
    print(f"Youden t={t_y:.3f}: sens={sensy:.3f} spec={specy:.3f}")

    # 4. Calibration
    brier = brier_score_loss(label, avg)
    ece, mce = expected_calibration_error(label, avg)
    print(f"\nBrier={brier:.4f}  ECE={ece:.4f}  MCE={mce:.4f}")

    # 5. Decision-curve net benefit
    print("\nDecision-curve net benefit (run-averaged):")
    nb = {}
    for pt in THRESHOLDS:
        nb[pt] = net_benefit(label, avg, pt)
        prev = label.mean()
        nb_all = prev - (1 - prev) * pt / (1 - pt)
        print(f"  pt={pt:.2f}: NB={nb[pt]:+.4f}  (treat-all={nb_all:+.4f})")

    # 6. Paired DeLong vs each DL baseline
    print("\nPaired DeLong vs DL baselines:")
    delong = {}
    avg_df = pd.DataFrame({"aid": aids, "label": label, "confidence": avg})
    for name, fn in DL_FILES.items():
        dl = load_dl(LUNA25_DL_PRED_DIR / fn)
        merged = avg_df.merge(dl[["aid", "confidence"]], on="aid", suffixes=("_vlm", "_dl"))
        y = merged["label"].values.astype(int)
        sa = merged["confidence_vlm"].values.astype(float)
        sb = merged["confidence_dl"].values.astype(float)
        auc_vlm, auc_dl, p = delong_p_value(y, sa, sb)
        delong[name] = {"auc_dl": auc_dl, "auc_vlm_on_intersection": auc_vlm,
                        "n": len(merged), "delong_p": p}
        print(f"  {name:15s} AUC_DL={auc_dl:.4f}  AUC_VLM={auc_vlm:.4f}  n={len(merged)}  P={p:.3g}")

    # 7. Paired DeLong vs Brock on 701-case subset
    print("\nPaired DeLong vs Brock on complete-metadata subset:")
    brock = pd.read_csv(BROCK_CSV).rename(columns={"AnnotationID": "aid", BROCK_PROB_COL: "confidence"})
    merged = avg_df.merge(brock[["aid", "confidence"]], on="aid", suffixes=("_vlm", "_brock"))
    y = merged["label"].values.astype(int)
    sa = merged["confidence_vlm"].values.astype(float)
    sb = merged["confidence_brock"].values.astype(float)
    auc_vlm_s, auc_brock, p_brock = delong_p_value(y, sa, sb)
    print(f"  Brock           AUC_brock={auc_brock:.4f}  AUC_VLM={auc_vlm_s:.4f}  n={len(merged)}  P={p_brock:.3g}")

    # Also compute Brock subset CI for its own AUC
    brock_lo, brock_hi = stratified_bootstrap(y, sb, roc_auc_score)
    vlm_sub_lo, vlm_sub_hi = stratified_bootstrap(y, sa, roc_auc_score)
    print(f"  Brock 95% CI on subset: {brock_lo:.4f}-{brock_hi:.4f}")
    print(f"  VLM   95% CI on subset: {vlm_sub_lo:.4f}-{vlm_sub_hi:.4f}")

    # 8. Save metrics JSON
    out = {
        "n_runs": len(F3_REPLICATES),
        "n_cases": len(aids),
        "individual_run_aucs": [round(a, 4) for a in individual_aucs],
        "five_run_mean_auc": round(float(np.mean(individual_aucs)), 4),
        "five_run_sd_auc": round(float(np.std(individual_aucs, ddof=1)), 4),
        "run_averaged_auc": round(auc, 4),
        "run_averaged_auc_ci": [round(auc_lo, 4), round(auc_hi, 4)],
        "run_averaged_prauc": round(prauc, 4),
        "run_averaged_prauc_ci": [round(pr_lo, 4), round(pr_hi, 4)],
        "sens_at_0p5": round(sens5, 3),
        "spec_at_0p5": round(spec5, 3),
        "youden_threshold": round(t_y, 3),
        "sens_at_youden": round(sensy, 3),
        "spec_at_youden": round(specy, 3),
        "brier": round(brier, 4),
        "ece": round(ece, 4),
        "mce": round(mce, 4),
        "net_benefit": {str(pt): round(v, 4) for pt, v in nb.items()},
        "delong_vs_dl": {k: {**v, "auc_dl": round(v["auc_dl"], 4),
                             "auc_vlm_on_intersection": round(v["auc_vlm_on_intersection"], 4),
                             "delong_p": float(f"{v['delong_p']:.4g}")}
                          for k, v in delong.items()},
        "brock_subset": {
            "n": int(len(merged)),
            "auc_vlm": round(auc_vlm_s, 4),
            "auc_vlm_ci": [round(vlm_sub_lo, 4), round(vlm_sub_hi, 4)],
            "auc_brock": round(auc_brock, 4),
            "auc_brock_ci": [round(brock_lo, 4), round(brock_hi, 4)],
            "delong_p": float(f"{p_brock:.4g}"),
        },
    }
    out_json = VLM_RESULTS_DIR / "f3a_mean_of5_metrics.json"
    out_json.write_text(json.dumps(out, indent=2))
    print(f"\n-> {out_json}")


if __name__ == "__main__":
    main()
